/* ============================================================
   «اسمش با «م» شروع می‌شه؟» — شیطنتِ آخرِ بازی.

   وقتی عمه تقریباً مطمئن است، پرسیدنِ حرفِ اول همان لحظه‌ای است که بازیکن
   جا می‌خورد: «وای، داره می‌گه!». پس این‌ها فقط در دروازه‌ی موتور باز
   می‌شوند (ENG.rankQuestions: نامزدِ اول بالای LETTER_GATE و حداکثر یک
   بار در هر دست) — اگر آزاد بودند، از همان سؤالِ سوم با «ب؟ م؟ س؟» بازی
   را به بیست‌سؤالیِ الفبایی تبدیل می‌کردند.

   قاعده از نام می‌خواند، نه برچسب: generate.js نام را در t.__name می‌گذارد.
   برای نسبتِ فامیلی ۰.۵ است — حرفِ اولِ «خاله» ربطی به اسمِ خاله ندارد.
   ============================================================ */

const LETTERS = ['ا','ب','پ','ت','ج','چ','ح','خ','د','ر','ز','ژ','س','ش','ص','ط','ع','غ','ف','ق','ک','گ','ل','م','ن','و','ه','ی','ث','ذ','ض','ظ'];

const first = name => {
  const c = String(name).trim().replace(/^[«"'(]/, '')[0] || '';
  return ({'آ':'ا','أ':'ا','إ':'ا','ي':'ی','ك':'ک'})[c] || c;
};

const LETTER_QUESTIONS = LETTERS.map((L, i) => ({
  id: 'ltr' + i, cluster: 'letter',
  text: `یه سؤالِ شیطونی: اسمش با «${L === 'ا' ? 'الف' : L}» شروع می‌شه؟`,
  rule: t => t.has('kin') ? .5 : first(t.__name) === L ? .9 : .04,
}));

module.exports = { LETTER_QUESTIONS, first };
